// Renders the brand SVGs in brand/ into: the macOS app icon (AppIcon.icns), a Windows-style .ico kept for reference, and
// Sources/ChaeDiewKit/BrandAssets.swift (small PNGs embedded as base64, so the app needs no resource bundle).
// Run: swiftc -O scripts/make-brand-assets.swift -o /tmp/make-brand-assets && /tmp/make-brand-assets
import AppKit

let root = FileManager.default.currentDirectoryPath
func read(_ name: String) -> String { (try? String(contentsOfFile: "\(root)/brand/\(name)", encoding: .utf8)) ?? { fatalError("missing brand/\(name)") }() }

/// Renders SVG text to a PNG of `width` × height (keeping the SVG's aspect ratio).
func render(svg: String, width: Int, scale: CGFloat = 1) -> Data {
    let tmp = URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent("brand-\(UUID().uuidString).svg")
    try! svg.write(to: tmp, atomically: true, encoding: .utf8)
    defer { try? FileManager.default.removeItem(at: tmp) }
    let image = NSImage(contentsOf: tmp)!
    let aspect = image.size.height / image.size.width
    let w = Int(CGFloat(width) * scale), h = Int((CGFloat(width) * aspect * scale).rounded())
    let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: w, pixelsHigh: h, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true,
                               isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
    NSGraphicsContext.current?.imageInterpolation = .high
    image.draw(in: NSRect(x: 0, y: 0, width: w, height: h), from: .zero, operation: .sourceOver, fraction: 1)
    NSGraphicsContext.restoreGraphicsState()
    return rep.representation(using: .png, properties: [:])!
}

/// Crops a PNG to the bounding box of its non-transparent pixels.
func trimmed(_ png: Data) -> Data {
    guard let rep = NSBitmapImageRep(data: png), let cg = rep.cgImage else { return png }
    let w = cg.width, h = cg.height
    var px = [UInt8](repeating: 0, count: w * h * 4)
    let ctx = CGContext(data: &px, width: w, height: h, bitsPerComponent: 8, bytesPerRow: w * 4, space: CGColorSpaceCreateDeviceRGB(),
                        bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
    ctx.draw(cg, in: CGRect(x: 0, y: 0, width: w, height: h))
    var minX = w, minY = h, maxX = -1, maxY = -1
    for y in 0..<h { for x in 0..<w where px[(y * w + x) * 4 + 3] > 8 { minX = min(minX, x); maxX = max(maxX, x); minY = min(minY, y); maxY = max(maxY, y) } }
    guard maxX >= 0, let crop = cg.cropping(to: CGRect(x: minX, y: minY, width: maxX - minX + 1, height: maxY - minY + 1)) else { return png }
    return NSBitmapImageRep(cgImage: crop).representation(using: .png, properties: [:])!
}

// 1. App icon
let appIconSVG = read("chaediew-icon-small-app.svg")
let iconset = "\(root)/brand/build/AppIcon.iconset"
try? FileManager.default.removeItem(atPath: "\(root)/brand/build")
try! FileManager.default.createDirectory(atPath: iconset, withIntermediateDirectories: true)
for (name, px) in [("icon_16x16", 16), ("icon_16x16@2x", 32), ("icon_32x32", 32), ("icon_32x32@2x", 64), ("icon_128x128", 128), ("icon_128x128@2x", 256),
                   ("icon_256x256", 256), ("icon_256x256@2x", 512), ("icon_512x512", 512), ("icon_512x512@2x", 1024)] {
    try! render(svg: appIconSVG, width: px).write(to: URL(fileURLWithPath: "\(iconset)/\(name).png"))
}
let task = Process()
task.executableURL = URL(fileURLWithPath: "/usr/bin/iconutil")
task.arguments = ["-c", "icns", iconset, "-o", "\(root)/brand/build/AppIcon.icns"]
try! task.run(); task.waitUntilExit()
print("AppIcon.icns:", task.terminationStatus == 0 ? "ok" : "FAILED")

// 2. Embedded in-app images
let darkInk = "#15171C", lightInk = "#F5F7FA"
let wordmark = read("chaediew-wordmark-A-snap-light.svg")
let wordmarkOnDark = wordmark.replacingOccurrences(of: darkInk, with: lightInk)
let mark = read("chaediew-icon-small-mark.svg")
let markOnDark = mark.replacingOccurrences(of: darkInk, with: lightInk)
let assets: [(String, Data)] = [
    ("wordmarkOnDark", trimmed(render(svg: wordmarkOnDark, width: 900))),
    ("wordmarkOnLight", trimmed(render(svg: wordmark, width: 900))),
    ("markOnDark", render(svg: markOnDark, width: 96)),
    ("markOnLight", render(svg: mark, width: 96)),
    ("appIcon", render(svg: appIconSVG, width: 256)),
]
var source = "import AppKit\n\n/// Generated by scripts/make-brand-assets.swift from brand/*.svg. Do not edit by hand.\nenum BrandAssets {\n"
for (name, data) in assets {
    source += "    static let \(name)Base64 = \"\(data.base64EncodedString())\"\n"
}
source += "}\n"
try! source.write(toFile: "\(root)/Sources/ChaeDiewKit/BrandAssets.swift", atomically: true, encoding: .utf8)
print("BrandAssets.swift:", assets.map { "\($0.0) \($0.1.count / 1024) KB" }.joined(separator: ", "))
